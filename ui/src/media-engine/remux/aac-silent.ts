/**
 * 取静音帧字节。`codec` 为 mp4a.40.2（LC-AAC）时用 LC 表，其余（HE-AAC：mp4a.40.5/40.29）
 * 用 HE 表；无该声道数的静音帧时返回 null（调用方应退化为"不挂假音轨"）。
 */
export function getSilentFrame(codec: string, channelCount: number): Uint8Array | null {
  const table = codec === "mp4a.40.2" ? LC_SILENT : HE_SILENT;
  const bytes = table[channelCount];
  return bytes ? new Uint8Array(bytes) : null;
}
